"""Shared-contract parity for the terminal failed-turn copy surfaces.

The Go twin (internal/turnfailure) is the canonical statement of the
contract the runtime executes in agent/turn_failure_copy.py plus the two
gateway boundary helpers (_hmwa_add_failed_turn_notice /
_hmwa_close_failed_turn in gateway/run_turn.py) and the shutdown interrupt
tool category (gateway/run_shutdown.py). The shared table
(internal/turnfailure/testdata/turnfailure_cases.json) was generated by
driving the real Python functions, so every row's ``expect`` IS the Python
answer; this file proves (1) the Python functions still answer what the
table records and (2) the built Go twin answers identically for every row.
The Go tests run the same table in-process as a second cross-check.
"""

from __future__ import annotations

import asyncio
import json
import subprocess
from pathlib import Path
from types import SimpleNamespace

import pytest

from agent.turn_failure_copy import (
    SITE_FAILURE_CODES, _FAILURE_CODE_COPY, _ONE_OFF_COPY, exhausted_copy,
    exit_reason_failure, failure_cause_gloss, failed_turn_notice,
    invalid_response_failure_reason, site_copy, stamp_failure,
)
from gateway.run_shutdown import _interrupt_tool_reason
from gateway.run_turn import GatewayTurnMixin

_REPO = Path(__file__).resolve().parents[2]
_TABLE = _REPO / "internal" / "turnfailure" / "testdata" / "turnfailure_cases.json"


def _shared_cases():
    return json.loads(_TABLE.read_text(encoding="utf-8"))["cases"]


class _TailStore:
    """Minimal async store double for the boundary tail gate."""

    def __init__(self, tail):
        self.tail = tail
        self.appended = []

    async def transcript_tail_role(self, session_id):
        return self.tail

    async def append_to_transcript(self, session_id, row):
        self.appended.append(row)


def _python_answer(case) -> object:
    op = case["op"]
    if op == "site_code":
        return {"member": case["code"] in SITE_FAILURE_CODES}
    if op == "exit_reason_failure":
        verdict = exit_reason_failure(case["reason"])
        if verdict is None:
            return None
        return {"reason": verdict.reason, "retryable": verdict.retryable, "fails_turn": verdict.fails_turn}
    if op == "invalid_response_reason":
        via = case["code_via"]
        if via == "none":
            response = None
        elif via == "no_error":
            response = SimpleNamespace()
        elif via == "attr":
            response = SimpleNamespace(error=SimpleNamespace(code=case["code"]))
        elif via == "dict":
            response = SimpleNamespace(error={"code": case["code"]})
        elif via == "error_none":
            response = SimpleNamespace(error=None)
        else:  # pragma: no cover - generator guarantees a known via
            raise AssertionError(via)
        return {"reason": invalid_response_failure_reason(response)}
    if op == "failed_turn_notice":
        rows = [
            {"role": m["role"], **({"tool_calls": [{"id": "x"}]} if m.get("tool_calls") else {})}
            for m in case["messages"]
        ]
        return {"notice": failed_turn_notice(rows)}
    if op == "add_failed_turn_notice":
        mixin = object.__new__(GatewayTurnMixin)
        return {"response": mixin._hmwa_add_failed_turn_notice(case["response"], case["notice"])}
    if op == "close_failed_turn":
        store = _TailStore(case["tail_role"])
        mixin = object.__new__(GatewayTurnMixin)
        mixin.async_session_store = store
        asyncio.run(mixin._hmwa_close_failed_turn("s1", "boundary"))
        return {"append": len(store.appended) == 1}
    if op == "interrupt_tool_reason":
        return {"tool_reason": _interrupt_tool_reason(case["reason"])}
    if op == "site_copy":
        return {"copy": site_copy(case["code"], **case["fields"])}
    if op == "exhausted_copy":
        return {"copy": exhausted_copy(
            case["reason"], label=case["label"], attempts=case["attempts"],
            summary=case["summary"], reset_seconds=case.get("reset_seconds"),
        )}
    if op == "failure_cause_gloss":
        kwargs = {}
        if "subject" in case:
            kwargs["subject"] = case["subject"]
        if "possessive" in case:
            kwargs["possessive"] = case["possessive"]
        return {"gloss": failure_cause_gloss(case["reason"], **kwargs)}
    if op == "stamp_failure":
        result = {"final_response": "kept"}
        stamp_failure(result, case["reason"], case["retryable"])
        assert result["final_response"] == "kept"
        return {"failure_reason": result["failure_reason"], "failure_retryable": result["failure_retryable"]}
    raise AssertionError(op)


@pytest.mark.parametrize("case", _shared_cases(), ids=lambda c: c["name"])
def test_python_answers_the_shared_table(case):
    assert _python_answer(case) == case["expect"]


@pytest.fixture(scope="session")
def go_turnfailure(tmp_path_factory) -> str | None:
    """Build cmd/turnfailure once per session; None when no Go toolchain."""
    binary = tmp_path_factory.mktemp("turnfailure-bin") / "turnfailure"
    build = subprocess.run(
        ["go", "build", "-o", str(binary), "./cmd/turnfailure"],
        cwd=str(_REPO / "internal" / "turnfailure"),
        capture_output=True, text=True, timeout=300,
    )
    if build.returncode != 0:
        if "cannot find \"go\"" in build.stderr or "executable file not found" in build.stderr:
            return None
        pytest.fail(f"go build cmd/turnfailure failed:\n{build.stderr}")
    return str(binary)


@pytest.mark.parametrize("case", _shared_cases(), ids=lambda c: c["name"])
def test_go_binary_answers_the_shared_table(case, go_turnfailure):
    if go_turnfailure is None:
        pytest.skip("no Go toolchain")
    run = subprocess.run(
        [go_turnfailure], input=json.dumps(case), capture_output=True, text=True, timeout=60,
    )
    assert run.returncode == 0, run.stderr
    assert json.loads(run.stdout) == case["expect"]


# ---- invariants (both engines, beyond the table) --------------------------

def test_unknown_site_code_raises_and_the_binary_refuses(go_turnfailure):
    """site_copy must refuse unknown codes loudly, not render empty copy."""
    with pytest.raises(KeyError):
        site_copy("nope")
    if go_turnfailure is None:
        pytest.skip("no Go toolchain")
    run = subprocess.run(
        [go_turnfailure], input=json.dumps({"op": "site_copy", "code": "nope", "fields": {}}),
        capture_output=True, text=True, timeout=60,
    )
    assert run.returncode != 0
    assert "nope" in run.stderr


def test_every_site_code_copy_relationship():
    """empty_response/session_busy are worded by other surfaces by design;
    every other site code carries a failure-code copy row, and the merged
    site table is exactly the failure-code rows plus the one-off rows."""
    assert set(_FAILURE_CODE_COPY) == SITE_FAILURE_CODES - {"empty_response", "session_busy"}
    assert set({**_FAILURE_CODE_COPY, **_ONE_OFF_COPY}) == set(_FAILURE_CODE_COPY) | set(_ONE_OFF_COPY)


_SITE_COPY_FIELDS = {"model", "label", "attempts", "detail", "resume", "tokens", "window", "limit", "preview"}


def test_site_copy_templates_only_use_known_fields():
    """A new template field must update the Go twin's format engine (and the
    Python _Defaults contract) deliberately — this pins the vocabulary."""
    import re

    for code, template in {**_FAILURE_CODE_COPY, **_ONE_OFF_COPY}.items():
        for name in re.findall(r"\{([a-z_]+)[:}]", template):
            assert name in _SITE_COPY_FIELDS, f"{code} uses unknown field {name}"


def test_close_boundary_never_stacks_a_second_row():
    """Only an open user tail appends; already-closed turns stay closed."""
    for tail in ("assistant", "tool", "", "User"):
        store = _TailStore(tail)
        mixin = object.__new__(GatewayTurnMixin)
        mixin.async_session_store = store
        asyncio.run(mixin._hmwa_close_failed_turn("s1", "boundary"))
        assert store.appended == []


def test_notice_switches_on_tool_evidence_not_position():
    rows = [
        {"role": "user"}, {"role": "assistant"}, {"role": "tool"},
        {"role": "user"}, {"role": "assistant"},
    ]
    assert failed_turn_notice(rows).startswith("This turn did not complete")
    assert failed_turn_notice([{"role": "user"}]).startswith("Your request was not processed")
