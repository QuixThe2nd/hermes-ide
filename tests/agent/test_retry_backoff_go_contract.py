"""Shared-contract parity for the retry/backoff decision core.

The Go twin (internal/retrybackoff) is the canonical statement of the
contract the runtime executes in agent/retry_utils.py (Retry-After parsing,
jittered backoff, the Z.AI Coding overload schedule, free-text reset
grammars) plus the wait-and-surface choice of
agent/turn_recovery.py::compute_error_backoff. The shared table
(internal/retrybackoff/testdata/retrybackoff_cases.json) was generated by
driving the real Python functions with datetime pinned and the jitter draw
patched to its base for the deterministic ops, so every row's ``expect`` IS
the Python answer; this file proves (1) the Python functions still answer
what the table records and (2) the built Go twin answers identically for
every row. The Go tests run the same table in-process as a second
cross-check.
"""

from __future__ import annotations

import json
import subprocess
from datetime import datetime
from datetime import timezone
from pathlib import Path
from types import SimpleNamespace

import pytest

import agent.retry_utils as retry_utils
from agent.retry_utils import (
    adaptive_rate_limit_backoff, format_reset_window, is_zai_coding_overload_error,
    jittered_backoff, parse_retry_after_seconds, reset_delay_from_message,
    zai_coding_overload_retry_ceiling,
)
from agent.turn_recovery import compute_error_backoff

_REPO = Path(__file__).resolve().parents[2]
_TABLE = _REPO / "internal" / "retrybackoff" / "testdata" / "retrybackoff_cases.json"

FIXED_NOW = datetime(2026, 11, 24, 12, 0, 0, tzinfo=timezone.utc)


def _shared_cases():
    return json.loads(_TABLE.read_text(encoding="utf-8"))["cases"]


class _FixedDatetime:
    @staticmethod
    def now(tz=None):
        return FIXED_NOW


def _fake_jittered(attempt, *, base_delay=5.0, max_delay=120.0, jitter_ratio=0.5):
    """Deterministic stand-in: the base exactly (jitter_ratio=0 semantics)."""
    exponent = max(0, attempt - 1)
    return max_delay if (exponent >= 63 or base_delay <= 0) else min(base_delay * (2 ** exponent), max_delay)


class _FakeAgent:
    def __init__(self):
        self.calls = []

    def _emit_diagnostic_status(self, s):
        self.calls.append("emit")

    def _buffer_diagnostic_status(self, s):
        self.calls.append("buffer")

    def _emit_diagnostic_wait(self, s):
        pass

    def _client_log_context(self):
        return "ctx"


class _FakeAPIError(Exception):
    """Exception-shaped carrier: compute_error_backoff is typed for
    exceptions and _error_text flattens str(error) too."""

    def __init__(self, **attrs):
        super().__init__(attrs.get("message", ""))
        for key, value in attrs.items():
            setattr(self, key, value)


def _surface_error(case):
    headers = None
    if case.get("retry_after_via") == "header":
        headers = {"Retry-After": str(case["retry_after"])}
    body = None
    via = case.get("retry_after_via")
    if via == "body_nested":
        body = {"error": {"retry_after": case["retry_after"], "message": "slow down"}}
    elif via == "body_top":
        body = {"retry_after": case["retry_after"]}
    if case.get("zai"):
        message, status = "code 1305: service may be temporarily overloaded", 429
    else:
        message, status = "Too many requests", case.get("status_code", 429)
    return _FakeAPIError(
        status_code=status, message=message, body=body,
        response=SimpleNamespace(headers=headers),
    )


@pytest.fixture
def pinned_retry_utils(monkeypatch):
    """Patch points the deterministic rows depend on, restored per test."""
    monkeypatch.setattr(retry_utils, "datetime", _FixedDatetime)
    monkeypatch.setattr(retry_utils, "jittered_backoff", _fake_jittered)
    yield monkeypatch


def _python_answer(case, monkeypatch) -> object:
    op = case["op"]
    if op == "parse_retry_after":
        # The datetime patch only matters for HTTP-date rows.
        monkeypatch.setattr(retry_utils, "datetime", _FixedDatetime)
        try:
            return {"wait": parse_retry_after_seconds(case["raw"])}
        finally:
            monkeypatch.undo()
    if op == "jittered_base":
        return {"base": jittered_backoff(
            case["attempt"], base_delay=case["base_delay"], max_delay=case["max_delay"], jitter_ratio=0.0,
        )}
    if op == "jitter_bounds":
        lo = _fake_jittered(case["attempt"], base_delay=case["base_delay"], max_delay=case["max_delay"])
        return {"lo": lo, "hi": lo * (1 + case["jitter_ratio"])}
    if op == "zai_overload":
        error = SimpleNamespace(status_code=case["status_code"], message=case["text"], body=None, response=None)
        return {"overload": is_zai_coding_overload_error(base_url=case["base_url"], model=case["model"], error=error)}
    if op == "adaptive_policy":
        monkeypatch.setattr(retry_utils, "is_zai_coding_overload_error", lambda **kw: case["zai"])
        wait, policy = adaptive_rate_limit_backoff(
            case["attempt"], base_url="https://api.z.ai/api/coding/paas/v4", model="glm-5.2",
            error=None, default_wait=case["default_wait"],
            short_attempts=case.get("short_attempts", retry_utils._ZAI_CODING_OVERLOAD_SHORT_ATTEMPTS),
        )
        return {"wait": wait, "policy": policy}
    if op == "zai_ceiling":
        return {"ceiling": zai_coding_overload_retry_ceiling(
            case.get("short_attempts", retry_utils._ZAI_CODING_OVERLOAD_SHORT_ATTEMPTS))}
    if op == "format_reset_window":
        return {"window": format_reset_window(case["seconds"])}
    if op == "reset_delay_from_message":
        return {"seconds": reset_delay_from_message(case["message"])}
    if op == "surface":
        agent = _FakeAgent()
        wait = compute_error_backoff(
            agent, _surface_error(case),
            retry_count=case["retry_count"], max_retries=case.get("max_retries", 8),
            is_rate_limited=case["is_rate_limited"], is_zai_coding_overload=case.get("zai", False),
            base_url=case.get("base_url", "https://openrouter.ai/api/v1"),
            model=case.get("model", "gpt-5"),
        )
        surface = "emit" if agent.calls == ["emit"] else "buffer"
        return {"wait": wait, "surface": surface}
    raise AssertionError(op)


_TABLE_CASES = _shared_cases()


@pytest.mark.parametrize("case", _TABLE_CASES, ids=lambda c: c["name"])
def test_python_answers_the_shared_table(case, pinned_retry_utils):
    assert _python_answer(case, pinned_retry_utils) == case["expect"]


@pytest.mark.parametrize("case", _TABLE_CASES, ids=lambda c: c["name"])
def test_go_binary_answers_the_shared_table(case, go_retrybackoff):
    if go_retrybackoff is None:
        pytest.skip("no Go toolchain")
    run = subprocess.run(
        [go_retrybackoff], input=json.dumps(case), capture_output=True, text=True, timeout=60,
    )
    assert run.returncode == 0, run.stderr
    assert json.loads(run.stdout) == case["expect"]


@pytest.fixture(scope="session")
def go_retrybackoff(tmp_path_factory) -> str | None:
    """Build cmd/retrybackoff once per session; None when no Go toolchain."""
    binary = tmp_path_factory.mktemp("retrybackoff-bin") / "retrybackoff"
    build = subprocess.run(
        ["go", "build", "-o", str(binary), "./cmd/retrybackoff"],
        cwd=str(_REPO / "internal" / "retrybackoff"),
        capture_output=True, text=True, timeout=300,
    )
    if build.returncode != 0:
        if "cannot find \"go\"" in build.stderr or "executable file not found" in build.stderr:
            return None
        pytest.fail(f"go build cmd/retrybackoff failed:\n{build.stderr}")
    return str(binary)


# ---- invariants (both engines, beyond the table) --------------------------

@pytest.mark.parametrize("case", [c for c in _TABLE_CASES if c["op"] == "jitter_bounds"],
                         ids=lambda c: c["name"])
def test_real_jitter_draw_stays_inside_the_envelope(case):
    """The envelope rows are containment contracts: the real uniform draw
    must land in [lo, hi] for every attempt shape."""
    for _ in range(20):
        draw = jittered_backoff(
            case["attempt"], base_delay=case["base_delay"],
            max_delay=case["max_delay"], jitter_ratio=case["jitter_ratio"],
        )
        assert case["expect"]["lo"] - 1e-9 <= draw <= case["expect"]["hi"] + 1e-9


def test_quota_grammar_beats_explicit_retry_after():
    """Credential-pool precedence: quotaResetDelay first, then an explicit
    "retry after Ns", then the resets_in_seconds field, then "resets in"."""
    assert reset_delay_from_message("quotaResetDelay: 200ms; retry after 30s") == 0.2
    assert reset_delay_from_message("retry after 30s; usage resets in 4hr") == 30
    assert reset_delay_from_message("usage resets in") is None


def test_retry_after_cap_and_zero_cooldown(monkeypatch):
    """compute_error_backoff applies the 600s cap and treats a zero/expired
    cooldown as absent (never hot-loop the provider). The jittered fallback
    is pinned to a sentinel because the run_agent conftest patches it for
    speed; what matters is that RA=0 routes to the jittered branch at all."""
    monkeypatch.setattr(retry_utils, "jittered_backoff", lambda attempt, **kw: 99.5)
    agent = _FakeAgent()
    error = _FakeAPIError(
        status_code=524, message="origin timeout", body=None,
        response=SimpleNamespace(headers={"Retry-After": "700"}),
    )
    assert compute_error_backoff(
        agent, error, retry_count=1, max_retries=8, is_rate_limited=False,
        is_zai_coding_overload=False, base_url="https://openrouter.ai/api/v1", model="gpt-5",
    ) == 600.0
    agent = _FakeAgent()
    error = _FakeAPIError(
        status_code=503, message="overloaded", body=None,
        response=SimpleNamespace(headers={"Retry-After": "0"}),
    )
    wait = compute_error_backoff(
        agent, error, retry_count=2, max_retries=8, is_rate_limited=False,
        is_zai_coding_overload=False, base_url="https://openrouter.ai/api/v1", model="gpt-5",
    )
    assert wait == 99.5


def test_zai_ceiling_covers_the_full_schedule():
    """The last long entry must be attempt ceiling-1: the loop gives up when
    retry_count >= ceiling BEFORE computing that attempt's backoff."""
    ceiling = zai_coding_overload_retry_ceiling()
    assert ceiling == retry_utils._ZAI_CODING_OVERLOAD_SHORT_ATTEMPTS + len(
        retry_utils._ZAI_CODING_OVERLOAD_LONG_BACKOFF) + 1


def test_go_binary_rejects_unknown_op(go_retrybackoff):
    if go_retrybackoff is None:
        pytest.skip("no Go toolchain")
    run = subprocess.run(
        [go_retrybackoff], input=json.dumps({"op": "nope"}),
        capture_output=True, text=True, timeout=60,
    )
    assert run.returncode != 0
    assert "unknown op" in run.stderr
